/// 本地内容跟地区的强弱关系：给页面上一句人话说明
String regionHint(Region r) {
  if (r.isNanling) {
    return r.isRural
        ? '${r.short}${r.town.isEmpty ? '' : ' · ${r.town}'}：先给你农村更常用的医保缴费、养老、农机补贴。'
        : '${r.short}：先给你县里更常办的就业、创业和社保补贴。';
  }
  return '${r.short}：本地自动抓取目前只接了南陵县，这里先给通用办事指北和省市官方渠道。';
}
