/// 一条本地办事指北。
///
/// 写这些条目有一条硬规矩：**不写具体金额、不写文号、不写人名**。
/// 补贴标准一年一变、经办窗口常搬、文件号只对某一版有效——把这类数字写死在
/// 一个闹钟应用里，用户照着跑一趟县城，窗口说「早改了」，这个 App 就再也不可信了。
/// 所以这里只写「谁能办、带什么、去哪办、什么时候别错过」，数字一律指向官方口径。
class LocalBrief {
  /// 音频文件名，l01..l06
  final String key;

  final String topic;
  final String title;

  /// 播报稿，也是屏幕上展开后的正文
  final String spoken;

  /// 办事要点，屏幕上分条列
  final List<String> steps;

  /// 「农村」优先 / 「县城」优先 / 都适用
  final List<String> prefer;

  const LocalBrief(this.key, this.topic, this.title, this.spoken, this.steps,
      {this.prefer = const ['县城', '农村', '乡镇', '城区']});

  /// 按当前居住类型排个序：农村人先看农机和医保，不会先看到创业贷款。
  static List<LocalBrief> forArea(String area) {
    final list = <LocalBrief>[...kLocalBriefs];
    list.sort((a, b) {
      final ra = a.prefer.contains(area) ? 0 : 1;
      final rb = b.prefer.contains(area) ? 0 : 1;
      return ra.compareTo(rb);
    });
    return list;
  }
}

